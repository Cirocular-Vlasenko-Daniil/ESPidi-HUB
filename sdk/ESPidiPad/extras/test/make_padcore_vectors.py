#!/usr/bin/env python3
"""Writes padcore_vectors.h: what PadCore.h must send, taken from the kit's Python reference
(../smc_pad_ble/ref/smc_pad_protocol.py), for test_padcore.cpp. Regenerate after changing the
kit or the test's fake pad; never edit the output by hand.

    python3 make_padcore_vectors.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "smc_pad_ble", "ref"))
import smc_pad_protocol as P  # noqa: E402

PROFILE = 2          # the fake pad's active profile


def region5():
    """The fake pad's region 5: the factory profile 8 times, byte [9] of pad record 0 = profile number."""
    out = bytearray()
    for p in range(8):
        prof = bytearray(P.default_profile())
        prof[P.PAD_OFF + 9] = p
        out += prof
    return bytes(out)


def quick_sequence(profile):
    """ESPidiPad without the full read: identity, region 4, the active profile in 1,009-byte reads."""
    out = [P.identity(), P.read(4, 0, P.REGION4_SIZE)]
    base = profile * P.PROFILE_SIZE
    for a in range(base, base + P.PROFILE_SIZE, P.READ_CHUNK):
        out.append(P.read(5, a, min(P.READ_CHUNK, base + P.PROFILE_SIZE - a)))
    return out


def c_array(name, data):
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    return f"static const uint8_t {name}[] = {{\n  " + ",\n  ".join(rows) + "\n};"


def packets(name, pkts):
    lens = ", ".join(str(len(p)) for p in pkts)
    return (c_array(name, b"".join(pkts)) + f"\nstatic const uint16_t {name}_LEN[] = {{{lens}}};\n"
            f"static const size_t {name}_COUNT = {len(pkts)};")


def render() -> str:
    r5 = region5()
    prof = r5[PROFILE * P.PROFILE_SIZE:(PROFILE + 1) * P.PROFILE_SIZE]
    bank1 = prof[P.PAD_OFF + 16 * P.PAD_SIZE:P.PAD_OFF + 32 * P.PAD_SIZE]
    colors = [(k * 10, 255 - k, k) for k in range(16)]
    parts = [
        "// generated by make_padcore_vectors.py from the kit's smc_pad_protocol.py: do not edit",
        "#pragma once", "#include <stddef.h>", "#include <stdint.h>",
        f"static const uint8_t FAKE_PROFILE = {PROFILE};",
        c_array("DEFAULT_PROFILE", P.default_profile()),
        packets("FULL_SEQUENCE", P.connect_sequence()),
        packets("QUICK_SEQUENCE", quick_sequence(PROFILE)),
        packets("QUICK_SEQUENCE_P3", quick_sequence(3)[2:]),
        c_array("COLOR_PAD3_RED", P.color_write(PROFILE, 3, (255, 0, 0))),
        c_array("BANK1_WRITE", P.write(5, P.pad_addr(PROFILE, 16), P.bank_colors(bank1, colors))),
    ]
    return "\n".join(parts) + "\n"


def main():
    with open(os.path.join(HERE, "padcore_vectors.h"), "w") as f:
        f.write(render())
    print("wrote padcore_vectors.h")


if __name__ == "__main__":
    main()
