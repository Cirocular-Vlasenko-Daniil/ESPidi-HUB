"""make_vectors.py: test vectors from the Python reference, for any other implementation of the protocol.

Writes ../vectors.json (language-neutral) and ../esp32/test/vectors.h (for test_protocol.cpp). Regenerate after any
change to smc_pad_protocol.py; never edit the outputs by hand.

    python make_vectors.py
"""
import json
from pathlib import Path

import smc_pad_protocol as P

HERE = Path(__file__).resolve().parent


def vectors():
    v = [
        ("identity", "identity()", P.identity()),
        ("read_region4", "read(4, 0, 12)", P.read(4, 0, 12)),
        ("read_region5_first", "read(5, 0, 1009)", P.read(5, 0, 1009)),
        ("read_region5_last", "read(5, 0x6E5C, 60)", P.read(5, 0x6E5C, 60)),
        ("color_p0_pad3_red", "color_write(0, 3, 255, 0, 0)", P.color_write(0, 3, (255, 0, 0))),
        ("color_p0_pad32_black", "color_write(0, 32, 0, 0, 0)", P.color_write(0, 32, (0, 0, 0))),
        ("color_p7_pad127_white", "color_write(7, 127, 255, 255, 255)", P.color_write(7, 127, (255, 255, 255))),
        ("write_region4_byte10", "write(4, 10, [1])", P.write(4, 10, b"\x01")),
        ("save_profiles", "save_profiles(true)", P.save_profiles(user_consented=True)),
        ("midi_to_pad_note", "midi_to_pad([0x90, 0x24, 0x7F])", P.midi_to_pad(b"\x90\x24\x7f")),
    ]
    return [{"name": n, "call": c, "bytes": b.hex(" ").upper()} for n, c, b in v]


def main():
    vs = vectors()
    (HERE.parent / "vectors.json").write_text(json.dumps({
        "_notice": "From the pi32v2_re project: Ruslan Mazavin, with Claude Opus 5.5 and Claude Opus 4.8. See NOTICE.md.",
        "generated_by": "ref/make_vectors.py from ref/smc_pad_protocol.py",
        "refused": ["read(0, 0, 4)", "write(3, 1, [0])", "write(5, 0x6E96, [1,2,3])", "read(5, 0x80000000, 1)",
                    "save_profiles(false)", "write(5, 0, [])"],
        "vectors": vs}, indent=1), encoding="utf-8")
    lines = ["// From the pi32v2_re project: Ruslan Mazavin, with Claude Opus 5.5 and Claude Opus 4.8. See NOTICE.md.",
             "// generated by ref/make_vectors.py: do not edit", "#pragma once", "#include <stdint.h>",
             "#include <stddef.h>", "struct Vec { const char* name; const uint8_t* bytes; size_t n; };"]
    for x in vs:
        b = bytes.fromhex(x["bytes"])
        lines.append(f"static const uint8_t V_{x['name']}[] = {{{', '.join(f'0x{c:02X}' for c in b)}}};")
    lines.append("static const Vec VECTORS[] = {")
    lines += [f"  {{\"{x['name']}\", V_{x['name']}, sizeof(V_{x['name']})}}," for x in vs]
    lines.append("};")
    out = HERE.parent / "esp32" / "test" / "vectors.h"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(vs)} vectors -> vectors.json, esp32/test/vectors.h")


if __name__ == "__main__":
    main()
