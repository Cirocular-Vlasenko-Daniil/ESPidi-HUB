#!/usr/bin/env python3
"""Generates web/font.js from hub/main/font.c, so the web preview draws the HUB's own font."""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

with open(os.path.join(ROOT, "hub", "main", "font.c")) as f:
    src = f.read()

glyphs = {}
for m in re.finditer(r"\{'(.)',\s*\{((?:\s*\"[.X]{5}\",?){7})\s*\}\}", src.replace("'\\''", "'")):
    rows = re.findall(r"\"([.X]{5})\"", m.group(2))
    glyphs[m.group(1)] = [int(r.replace("X", "1").replace(".", "0"), 2) for r in rows]

out = ("// Generated by tools/gen_web_font.py from hub/main/font.c — do not edit.\n"
       "// 5x7 glyphs: 7 row masks, bit 4 = leftmost column.\n"
       f"export const GLYPHS = {json.dumps(glyphs, separators=(',', ':'))};\n")
with open(os.path.join(ROOT, "web", "font.js"), "w") as f:
    f.write(out)
print(f"{len(glyphs)} glyphs -> web/font.js")
